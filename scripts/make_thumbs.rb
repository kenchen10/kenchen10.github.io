#!/usr/bin/env ruby
# Generates small preview images and records image dimensions for the site.
#
#   ruby scripts/make_thumbs.rb
#
# Run it from the repo root after adding photos to _data/images.yml,
# _data/birds.yml or _data/mural.yml, or an `image:` to _data/publications.yml,
# _data/otherpubs.yml or _data/news.yml. It:
#   1. writes a 640px JPEG preview of each album's cover (first image) to
#      images/thumbs/<album path>.jpg, used by the Photography grid and the
#      home page sidebar;
#   2. writes _data/image_sizes.yml with the width/height of every photo and
#      paper thumbnail, so pages can reserve the right space and don't jump
#      while images load.
# Existing previews are only regenerated when the original is newer.
# Uses macOS `sips`, so no extra installs are needed.

require 'yaml'
require 'fileutils'

ROOT = File.expand_path('..', __dir__)
Dir.chdir(ROOT)

THUMB_SIZE = 640

def sips_info(path)
  out = `sips -g pixelWidth -g pixelHeight -g orientation "#{path}" 2>/dev/null`
  w = out[/pixelWidth: (\d+)/, 1]&.to_i
  h = out[/pixelHeight: (\d+)/, 1]&.to_i
  o = out[/orientation: (\d+)/, 1]&.to_i
  return nil unless w && h
  # EXIF orientations 5-8 are rotated 90°, so the displayed size is swapped
  o && o >= 5 ? [h, w] : [w, h]
end

def thumb_path(img)
  "images/thumbs/#{img.sub(/\.[^.\/]+\z/, '')}.jpg"
end

albums = YAML.load_file('_data/images.yml') || []
birds  = YAML.load_file('_data/birds.yml') || []
mural  = YAML.load_file('_data/mural.yml') || []
papers = (YAML.load_file('_data/publications.yml') || []) + (YAML.load_file('_data/otherpubs.yml') || [])
news   = YAML.load_file('_data/news.yml') || []

sizes = {}
record = lambda do |path|
  return if sizes.key?(path)
  unless File.exist?(path)
    warn "missing: #{path}"
    return
  end
  info = sips_info(path)
  info ? sizes[path] = info : warn("unreadable: #{path}")
end

made = 0
albums.each do |album|
  imgs = album['imgs'] || []
  imgs.each { |img| record.call("images/#{img}") }
  next if imgs.empty?

  src = "images/#{imgs.first}"
  dest = thumb_path(imgs.first)
  next unless File.exist?(src)
  if !File.exist?(dest) || File.mtime(src) > File.mtime(dest)
    FileUtils.mkdir_p(File.dirname(dest))
    system('sips', '-Z', THUMB_SIZE.to_s, '-s', 'format', 'jpeg', '-s', 'formatOptions', '80',
           src, '--out', dest, out: File::NULL, err: File::NULL) or warn("failed: #{src}")
    made += 1
  end
  record.call(dest)
end

(birds + mural).each { |item| record.call(item['img']) if item['img'] }
(papers + news).each { |item| record.call("images/#{item['image']}") if item['image'] }

File.write('_data/image_sizes.yml',
           "# Generated by scripts/make_thumbs.rb — do not edit by hand.\n" +
           sizes.sort.map { |path, (w, h)| "#{path.inspect}: [#{w}, #{h}]" }.join("\n") + "\n")

puts "#{made} preview(s) written, #{sizes.size} image sizes recorded."
